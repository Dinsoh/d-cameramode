from pathlib import Path
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1920,'height':1080})
    root=Path(__file__).resolve().parents[1]/'d-photomode/html'
    page.route('http://photomode.test/**', lambda route: route.fulfill(path=str(root / (route.request.url.rsplit('/',1)[-1] or 'index.html'))))
    page.goto('http://photomode.test/index.html')
    page.evaluate("() => { window.GetParentResourceName=()=> 'd-photomode'; window.calls=[]; window.fetch=async (url,opts)=>{calls.push([url,JSON.parse(opts.body)]);return {ok:true,json:async()=>({ok:true})}}; }")
    page.evaluate("window.postMessage({action:'open',fov:{min:20,max:80,default:70},tilt:15,filters:[{label:'Natural'},{label:'Soft'}],dof:true,hideKey:'H'},'*')")
    page.locator('#panel').wait_for(state='visible')
    assert page.locator('#fov').input_value()=='70'
    page.locator('#tabLook').click()
    page.locator('#filter').select_option('2')
    page.locator('#strength').fill('0.3'); page.locator('#strength').dispatch_event('input'); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[1].strength===0.3&&c[1].fov===70)")
    page.locator('#tabFrame').click()
    page.locator('#guide').select_option('golden'); assert page.locator('#grid').get_attribute('data-guide')=='golden'
    page.locator('#ratio').select_option('1'); assert page.locator('#bars').evaluate("el=>parseFloat(el.style.borderLeftWidth)>0")
    page.locator('#tabLook').click()
    page.locator('#focus').fill('2'); page.locator('#focus').dispatch_event('input'); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[1].focus===2&&c[1].fov===70)")
    page.locator('#tabCamera').click()
    page.locator('#fov').fill('35'); page.locator('#fov').dispatch_event('input'); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[0].endsWith('/update')&&c[1].fov===35)")
    page.locator('#tabFrame').click()
    page.locator('#showGrid').check(); assert page.locator('#grid').is_visible()
    page.locator('#reset').click(); assert page.locator('#fov').input_value()=='70'; assert not page.locator('#grid').is_visible()
    page.keyboard.press('h'); assert page.evaluate("calls.some(c=>c[0].endsWith('/hide'))")
    page.evaluate("window.postMessage({action:'hidden',hidden:true},'*')"); page.locator('#frame').wait_for(state='hidden')
    page.evaluate("window.postMessage({action:'hidden',hidden:false},'*')"); page.locator('#frame').wait_for(state='visible')
    page.keyboard.press('Escape'); assert page.evaluate("calls.some(c=>c[0].endsWith('/close'))")
    page.evaluate("window.postMessage({action:'open',fov:{min:20,max:80,default:70},tilt:15,filters:[{label:'Natural'}],dof:false,hideKey:'H',orbit:{distance:{min:1,max:3,default:2},height:{min:-0.4,max:1.5,default:0.2}}},'*')")
    page.locator('#orbit').wait_for(state='visible')
    page.locator('[data-angle="180"]').click(); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[0].endsWith('/update')&&c[1].angle===180)")
    page.locator('#distance').fill('2.5'); page.locator('#distance').dispatch_event('input'); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[1].distance===2.5)")
    page.locator('#reset').click(); assert page.locator('#angle').input_value()=='0'; assert page.locator('#distance').input_value()=='2'
    page.set_viewport_size({'width':1280,'height':720})
    bounds=page.locator('#panel').bounding_box(); assert bounds['y']>=0 and bounds['y']+bounds['height']<=720
    page.screenshot(path='/workspace/photomode-ui.png',omit_background=True)
    page.locator('#capture').click(); page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[0].endsWith('/capture'))")
    page.evaluate("window.postMessage({action:'prepareCapture',id:10},'*')")
    page.locator('#frame').wait_for(state='hidden'); page.wait_for_timeout(100)
    assert page.evaluate("calls.some(c=>c[0].endsWith('/captureReady')&&c[1].id===10)")
    assert page.locator('#captureStatus').is_hidden()
    page.evaluate("window.postMessage({action:'captured'},'*')"); page.locator('#captureStatus').wait_for(state='visible')
    page.evaluate("window.postMessage({action:'printing',duration:1800},'*')"); page.wait_for_function("document.getElementById('captureStatus').classList.contains('printing')")
    page.evaluate("window.postMessage({action:'captureResult',ok:true,message:'Photograph printed.',hidden:false},'*')")
    page.locator('#frame').wait_for(state='visible'); assert page.locator('#capture').is_enabled()
    assert page.locator('#captureMessage').inner_text()=='Photograph printed.'
    page.evaluate("window.postMessage({action:'close'},'*')"); page.locator('#frame').wait_for(state='hidden')
    print('PASS: UI open/update, grid, reset, hide/restore, exit, 720p fit, close')
    # New eye-level mode: a clean viewfinder by default, settings opt in.
    page.set_viewport_size({'width':1280,'height':720})
    page.evaluate("window.postMessage({action:'open',viewfinder:true,orbit:{distance:{min:0.5,max:6,default:2},height:{min:-1,max:3,default:0.2}},fov:{min:20,max:90,default:70},tilt:15,filters:[{label:'Natural'}],dof:false,hideKey:'H'},'*')")
    page.locator('#viewfinderHud').wait_for(state='visible')
    assert page.locator('#panel').is_hidden()
    assert page.locator('#lensValue').inner_text()=='1.0×'
    page.evaluate("window.postMessage({action:'lens',fov:35},'*')")
    page.wait_for_function("document.getElementById('fov').value==='35'")
    assert page.locator('#lensValue').inner_text()=='2.2×'
    page.evaluate("window.postMessage({action:'settings',open:true},'*')")
    page.locator('#panel').wait_for(state='visible')
    assert page.locator('#orbit').is_hidden()
    page.locator('#cameraMode').select_option('selfie'); page.locator('#cameraMode').dispatch_event('input')
    page.locator('#orbit').wait_for(state='visible')
    page.locator('#cameraPose').uncheck()
    page.locator('#distance').fill('5.61'); page.locator('#distance').dispatch_event('input')
    page.locator('#height').fill('2.87'); page.locator('#height').dispatch_event('input')
    page.wait_for_timeout(150)
    assert page.evaluate("calls.some(c=>c[1].mode==='selfie'&&c[1].pose===false&&c[1].distance===5.61&&c[1].height===2.87)")
    page.locator('#tabFrame').click()
    page.locator('#caption').fill('A photo with H and Return')
    before=page.evaluate('calls.length')
    page.locator('#caption').press('h')
    page.wait_for_timeout(50)
    assert page.evaluate('calls.length')==before
    page.evaluate("window.postMessage({action:'settings',open:false},'*')")
    page.locator('#panel').wait_for(state='hidden')
    page.evaluate("window.postMessage({action:'prepareCapture',id:11},'*')")
    page.locator('#frame').wait_for(state='hidden')
    page.wait_for_function("calls.some(c=>c[0].endsWith('/captureReady')&&c[1].id===11)")
    page.evaluate("window.postMessage({action:'framing',fov:36.2,tilt:2.1,angle:12.3,distance:3.21,height:1.23},'*')")
    page.wait_for_function("document.getElementById('fov').value==='36.2'")
    assert page.locator('#distance').input_value()=='3.21'
    page.evaluate("window.postMessage({action:'captureResult',ok:true,hidden:false},'*')")
    page.locator('#viewfinderHud').wait_for(state='visible')
    assert page.locator('#panel').is_hidden()
    assert page.locator('#fov').input_value()=='36.2'
    page.evaluate("window.postMessage({action:'close'},'*')")
    page.locator('#frame').wait_for(state='hidden')
    print('PASS: clean viewfinder, lens sync, optional settings, caption typing, clean capture and lens preservation')
    # Reproduce the upstream canvas MIME issue in real Chromium, not a mocked encoder.
    encoding = page.evaluate("async()=>{const c=document.createElement('canvas');c.width=16;c.height=16;const encode=type=>new Promise(resolve=>c.toBlob(async blob=>resolve({type:blob.type,bytes:Array.from(new Uint8Array(await blob.arrayBuffer())).slice(0,3)}),type,0.85));return {jpg:await encode('image/jpg'),jpeg:await encode('image/jpeg')}}")
    assert encoding['jpg']['type']=='image/png'
    assert encoding['jpeg']['type']=='image/jpeg' and encoding['jpeg']['bytes'][:2]==[255,216]
    print('PASS: real canvas confirms jpg falls back to PNG; jpeg produces actual JPEG bytes')
    b.close()
